"""Write the bulk synthetic M5 corpus. Synthetic data only.

python -m satya_affidavit.synth --bulk DIR      # every profile x variant -> DIR (tests)

The committed demo cases are generated by `python -m satya_forensics.synth` (`make synth`).
"""

import argparse
import sys
from pathlib import Path

from satya_affidavit.synth.corpus import write_bulk


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m satya_affidavit.synth")
    parser.add_argument(
        "--bulk", type=Path, required=True, help="write every profile x variant here"
    )
    args = parser.parse_args(argv)
    count = write_bulk(args.bulk)
    print(f"wrote {count} synthetic cases to {args.bulk}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
