// WCAG 2.1 contrast check for style K (docs/prompts/PROMPT_ui_style_k.md section 4).
// Reads src/styles/tokens.json, measures every text/background pair the style uses and exits 1 on a failure.
// `--write` also writes docs/ui-style-k/CONTRAST.md. Run in T1 and T14.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(app, "src/styles/tokens.json"), "utf8"));
const k = t.k;
const c = t.color;

function lum(hex) {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
    .map((v) => v / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
    .reduce((s, v, i) => s + v * [0.2126, 0.7152, 0.0722][i], 0);
}
export function ratio(a, b) {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

// kind: text (>= 4.5), large (>= 3, text >= 24px or bold >= 19px), ui (>= 3, borders, focus ring, graphics)
const pairs = [];
const add = (kind, fg, bg, where) => pairs.push({ kind, fg, bg, where });
for (const bg of ["desk", "paper", "hover"]) {
  add("text", k.ink, k[bg], `body ink on ${bg}`);
  add("text", k.muted, k[bg], `muted labels on ${bg}`);
  add("text", k["accent-ink"], k[bg], `accent text under 24px on ${bg}`);
  add("large", k.accent, k[bg], `accent big numerals on ${bg}`);
  add("large", k.red, k[bg], `red big numerals on ${bg}`);
  add("text", k["red-ink"], k[bg], `mismatch text on ${bg}`);
  for (const s of ["verified", "mismatch", "expired", "pending", "unavailable", "review"]) {
    add("text", k[`st-${s}`], k[bg], `status label ${s} on ${bg}`);
  }
}
add("text", "#FFFFFF", k.accent, "primary button text on accent");
add("text", "#FFFFFF", k["accent-ink"], "primary button text on hover");
add("text", "#FFFFFF", k.ink, "pressed segment (white on ink)");
add("text", k["red-ink"], k["red-tint"], "differing row: red ink on tint");
add("text", k.ink, k["red-tint"], "ink on mismatch tint");
add("text", c["risk-high-ink"], c["risk-high"], "risk chip High");
add("text", c["risk-medium-ink"], c["risk-medium"], "risk chip Medium");
add("text", c["risk-low-ink"], c["risk-low"], "risk chip Low");
add("ui", k.ink, k.desk, "focus ring outer ink against desk");
add("ui", k.ink, k.paper, "focus ring outer ink against paper");
add("ui", k["rule-strong"], k.paper, "input border on paper");
add("ui", k.red, k.paper, "red edge on paper");
add("ui", k.agree, k.paper, "agrees edge and icon on paper");
add("ui", k.wait, k.paper, "waiting edge and icon on paper");
add("ui", k.check, k.paper, "person-must-check edge and icon on paper");

const need = { text: 4.5, large: 3, ui: 3 };
let failed = 0;
const rows = pairs.map((p) => {
  const r = ratio(p.fg, p.bg);
  const ok = r >= need[p.kind];
  if (!ok) failed++;
  return { ...p, r, ok };
});
for (const r of rows) console.log(`${r.ok ? "pass" : "FAIL"} ${r.r.toFixed(2).padStart(5)}:1 (needs ${need[r.kind]}) ${r.where} ${r.fg} on ${r.bg}`);
console.log(`${rows.length} pairs, ${failed} failed`);

if (process.argv.includes("--write")) {
  const out = join(app, "../../docs/ui-style-k/CONTRAST.md");
  mkdirSync(dirname(out), { recursive: true });
  const md = [
    "# Style K contrast report",
    "",
    "Generated by `apps/web/scripts/contrast-check.mjs --write` from `src/styles/tokens.json`. WCAG 2.1 AA: text 4.5:1, large text (24px, or bold 19px) 3:1, UI parts and focus ring 3:1.",
    "",
    "| Result | Ratio | Needs | Pair | Foreground | Background |",
    "|---|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.ok ? "pass" : "FAIL"} | ${r.r.toFixed(2)}:1 | ${need[r.kind]}:1 | ${r.where} | ${r.fg} | ${r.bg} |`),
    "",
    `${rows.length} pairs measured, ${failed} failed.`,
    "",
  ].join("\n");
  writeFileSync(out, md);
}
process.exit(failed ? 1 : 0);
