"""Render the P-1..P-19 backlog from docs/backlog/promises.json.

python3 infra/scripts/issues.py markdown       -> writes docs/ISSUES.md
python3 infra/scripts/issues.py tsv            -> id<TAB>title<TAB>labels (for create-issues.sh)
python3 infra/scripts/issues.py body P-3       -> issue body (markdown) for one promise
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = json.loads((ROOT / "docs/backlog/promises.json").read_text("utf-8"))


SPEC_FILES = {
    "01-design": "docs/specs/01-design-v2.2.1.md",
    "04-portal": "docs/specs/04-portal-integration-spec.md",
    "05-ui": "docs/specs/05-ui-design-spec.md",
}


def spec_ref(ref: str) -> str:
    short, _, rest = ref.partition(" ")
    return f"`{SPEC_FILES[short]}` {rest}" if short in SPEC_FILES else f"`{ref}`"


def title(issue: dict) -> str:
    return f"[{issue['id']}][{issue['module']}] {issue['claim']}"


def labels(issue: dict) -> list[str]:
    return [*issue["phase"], issue["prio"]]


def body(issue: dict) -> str:
    phase = " + ".join(p.replace("phase-", "Phase ") for p in issue["phase"])
    lines = [
        f"**Claim:** {issue['claim']}",
        f"**Module:** {issue['module']} · **Phase:** {phase} · **Priority:** {issue['prio']} (decision #40)",
        "",
        "**APH clauses involved:** " + ", ".join(issue["aph"]),
        "",
        "**Spec sections to read:**",
        *[f"- {spec_ref(s)}" for s in issue["specs"]],
        "",
        "**Acceptance criteria (draft):**",
        *[f"- [ ] {a}" for a in issue["ac"]],
        "",
        "**Synthetic data only.** No real institution names, people, IDs or documents in code, tests,",
        "fixtures, screenshots, logs or this issue (guard rails 3–5). Real samples stay in",
        "`data/real-samples/` on the team laptop and never enter a cloud session.",
        "",
        "Advisory only: no approve/reject/auto-clear control; every outbound event carries",
        '`advisory: true`, `regulatory_effect: "none"` (guard rail 1).',
    ]
    return "\n".join(lines)


def markdown() -> str:
    out = [
        "# Issue backlog: promises P-1 to P-19",
        "",
        "Generated by `infra/scripts/issues.py markdown` from `docs/backlog/promises.json` (source: "
        "`docs/specs/00-BUILD-CONTEXT.md`). The `gh` CLI was not authenticated in the slice 0 build "
        "session, so the issues are recorded here; run `infra/scripts/create-issues.sh` on a laptop "
        "with `gh auth login` to create them on GitHub (it skips titles that already exist).",
        "",
        "Priority labels follow decision #40 (hardest first): "
        + " → ".join(f"`prio-{i + 1}` {m}" for i, m in enumerate(DATA["priority_order"]))
        + ". M2 (P-19) and M10 (P-14) are not in that list; they are placed with M3 and M11 "
        "respectively (confirmed by the team, 26 Oct 2026).",
        "",
        "| Issue | Module | Phase | Priority |",
        "|---|---|---|---|",
    ]
    for i in DATA["issues"]:
        out.append(f"| {title(i)} | {i['module']} | {', '.join(i['phase'])} | {i['prio']} |")
    for i in DATA["issues"]:
        out += ["", f"## {title(i)}", f"Labels: `{'`, `'.join(labels(i))}`", "", body(i)]
    return "\n".join(out) + "\n"


def main() -> int:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "markdown"
    if cmd == "markdown":
        (ROOT / "docs/ISSUES.md").write_text(markdown(), "utf-8")
        print(f"wrote docs/ISSUES.md ({len(DATA['issues'])} issues)")
    elif cmd == "tsv":
        for i in DATA["issues"]:
            print(f"{i['id']}\t{title(i)}\t{','.join(labels(i))}")
    elif cmd == "body":
        print(body(next(i for i in DATA["issues"] if i["id"] == sys.argv[2])))
    else:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
